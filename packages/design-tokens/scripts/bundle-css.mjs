/**
 * Bundles the three CSS layers into one file, and into a JS module exporting
 * the same bytes as a string.
 *
 * The desktop app imports the CSS through Vite; the server has no bundler and
 * inlines the phone viewer's styles into an HTML <style> block, so it needs
 * the string form. Both come from the same source, which is the whole point —
 * the two platforms cannot drift apart.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const layers = ["tokens.css", "base.css", "components.css"];

const css = layers
  .map((name) => readFileSync(join(root, "src", name), "utf8"))
  .join("\n");

mkdirSync(join(root, "dist"), { recursive: true });
writeFileSync(join(root, "dist", "vault.css"), css);
writeFileSync(
  join(root, "dist", "css.js"),
  `// Generated by scripts/bundle-css.mjs — do not edit.\nexport const TOKENS_CSS = ${JSON.stringify(css)};\n`,
);
writeFileSync(
  join(root, "dist", "css.d.ts"),
  `// Generated by scripts/bundle-css.mjs — do not edit.\nexport declare const TOKENS_CSS: string;\n`,
);

console.log(`design-tokens: bundled ${layers.length} layers → ${css.length} bytes`);
