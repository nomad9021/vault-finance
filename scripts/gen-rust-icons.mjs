#!/usr/bin/env node
// Copies the icon paths from packages/ui/src/primitives/Icon.tsx into
// crates/vault-ui/src/ui/icons_gen.rs so React and Leptos pages draw the
// same glyphs. Run by scripts/build-rust-ui.mjs; `--check` fails if the
// committed file is stale (CI).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const src = readFileSync(`${root}packages/ui/src/primitives/Icon.tsx`, "utf8");
const body = src.slice(src.indexOf("const PATHS = {"), src.indexOf("} as const;"));
const entries = [...body.matchAll(/^\s*(\w+):\s*\n?\s*"([^"]+)"/gm)].map((m) => [m[1], m[2]]);
if (entries.length < 20) throw new Error(`only found ${entries.length} icons; did Icon.tsx change shape?`);

const out = `// @generated by scripts/gen-rust-icons.mjs from packages/ui/src/primitives/Icon.tsx. Do not edit.

/// SVG path data for an icon name (the same names as \`IconName\` in @vault/ui).
pub fn path(name: &str) -> Option<&'static str> {
    Some(match name {
${entries.map(([k, v]) => `        ${JSON.stringify(k)} => ${JSON.stringify(v)},`).join("\n")}
        _ => return None,
    })
}

pub const NAMES: [&str; ${entries.length}] = [${entries.map(([k]) => JSON.stringify(k)).join(", ")}];
`;

const target = `${root}crates/vault-ui/src/ui/icons_gen.rs`;
if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(target, "utf8"); } catch {}
  if (current !== out) {
    console.error("icons_gen.rs is stale: run node scripts/gen-rust-icons.mjs");
    process.exit(1);
  }
} else {
  writeFileSync(target, out);
  console.log(`wrote ${entries.length} icons`);
}
